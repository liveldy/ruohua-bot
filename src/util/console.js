/**
 * 子进程的编码垫子：面板起的服务、工具跑的命令都从这里过一遍。
 *
 * Windows 上的「命令行终端乱码」只有两个成因，这里各堵一个：
 *   1. 子进程压根没有控制台（detached + stdio ignore），或者控制台还是系统默认的 936 ——
 *      中文打出来就是乱码。起服务时用 `start` 开一个**已经设成 65001** 的控制台再跑目标，
 *      目标与它拉起的子进程都继承这个控制台。
 *   2. Python 这类按 locale 输出的程序，往管道里写就是 GBK，遇到表情符号还会直接
 *      UnicodeEncodeError —— 给它 PYTHONUTF8 / PYTHONIOENCODING，输出统一成 UTF-8。
 *
 * 其它平台没有这回事，一律原样执行（`consoleStart` 直接把命令透传出去）。
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

/** 垫片脚本的名字（放在 data/web/ 下，运行期生成）。 */
export const CONSOLE_LAUNCHER_NAME = 'console-utf8.bat';

/**
 * 「目标要在哪个目录里跑」从父进程传给垫片的方式。
 *
 * 为什么不靠 `spawn(..., { cwd })`：**Windows Terminal 不继承工作目录**，它按自己 profile 的
 * `startingDirectory`（这台机器上是 `%USERPROFILE%`）开命令行；于是 NapCat 那种
 * 「在自己目录里用相对路径调 `.\NapCatWinBootMain.exe`」的启动器就会报
 * 「'.\\NapCatWinBootMain.exe' is not recognized」（真机原案）。旧版 conhost 其实会继承，
 * 所以这份约定只是把它显式化：新老终端都按同一个目录跑。
 */
export const CONSOLE_CWD_VAR = 'RUOHUA_CWD';

/**
 * 垫片内容：必须是纯 ASCII + CRLF。
 * cmd.exe 按控制台代码页读 .bat，非 ASCII 的字节会让它从多字节字符中间断行。
 */
const LAUNCHER_SCRIPT = [
  '@echo off',
  'rem RuoHua console shim: switch this console to UTF-8, enter the working directory, then run the given command.',
  'rem Keep this file ASCII-only and CRLF. Generated by src/util/console.js.',
  'chcp 65001 >nul',
  `if not "%${CONSOLE_CWD_VAR}%"=="" cd /d "%${CONSOLE_CWD_VAR}%"`,
  '%*',
  '',
].join('\r\n');

const ensured = new Set();

/** 垫片脚本的路径。 */
export function consoleLauncherPath(dataDir) {
  return path.join(String(dataDir), 'web', CONSOLE_LAUNCHER_NAME);
}

/** 垫片内容（导出来给测试比字节）。 */
export function consoleLauncherScript() {
  return LAUNCHER_SCRIPT;
}

/** 按需写一次垫片；写不了就返回 null（调用方退回普通启动，不影响功能）。 */
export function ensureConsoleLauncher(dataDir, { write = true } = {}) {
  const file = consoleLauncherPath(dataDir);
  if (ensured.has(file)) return file;
  if (!write) return file;
  try {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === LAUNCHER_SCRIPT) {
      ensured.add(file);
      return file;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, LAUNCHER_SCRIPT, 'utf8');
    ensured.add(file);
    return file;
  } catch {
    return null;
  }
}

/**
 * 给子进程的环境：Python 侧统一按 UTF-8 输出（其它平台也留着，无害）。
 * extra 用来带上 `consoleStart()` 交代的额外变量（工作目录那个）。
 */
export function utf8Env(base = process.env, extra = null) {
  return { ...base, ...(extra ?? {}), PYTHONUTF8: '1', PYTHONIOENCODING: 'utf-8' };
}

/**
 * Windows Terminal 的 App Execution Alias（`%LOCALAPPDATA%\Microsoft\WindowsApps\wt.exe`）。
 *
 * 它是 0 字节的重解析点：`fs.existsSync()` 会当它不存在（会去解析那个不存在的小程序体），
 * 只能用 `lstatSync` 看它本身在不在。找不到就返回 null —— 调用方退回旧版控制台主机。
 */
export function windowsTerminalAlias({ platform = process.platform, env = process.env } = {}) {
  if (platform !== 'win32') return null;
  const base = String(env.LOCALAPPDATA ?? env.USERPROFILE ?? '').trim();
  if (!base) return null;
  const alias = path.join(base, 'Microsoft', 'WindowsApps', 'wt.exe');
  try {
    fs.lstatSync(alias);
    return alias;
  } catch {
    return null;
  }
}

/**
 * 起一个「自己有控制台、而且控制台是 UTF-8」的进程。
 *
 * 窗口优先交给 **Windows Terminal**（`terminal: 'windows-terminal'`）：这台机器上
 * `HKCU\Console\%%Startup` 没配过，直接 `start` 只会落到旧版控制台主机（conhost）——
 * 它和「管理员身份的窗口」长得一模一样，用户因此误判成提权了。有 wt 就走 wt，
 * 没有就还是 conhost，功能一样，只是窗口长相不同。
 *
 * @param {object} options
 * @param {string} options.target 要跑的程序（.bat / .exe / node）
 * @param {string[]} [options.args] 目标自己的参数
 * @param {string|null} [options.dataDir] 垫片写在哪里；没给就原样透传
 * @param {string|null} [options.cwd] 目标该在哪个目录里跑（放进返回的 env 里，垫片负责 cd）
 * @param {string} [options.platform]
 * @param {object} [options.env] 找 wt 别名用的环境（测试注入）
 * @param {'windows-terminal'|'conhost'|null} [options.terminal] 钉死用哪种窗口（测试注入），null = 自动
 * @returns {{ command: string, args: string[], launcher: string|null, terminal: string|null, env: object|null }}
 *   Windows 上是 `cmd /c start "" /min [<wt> -w -1 cmd /c] <垫片> <目标> <参数...>`，
 *   其它平台就是目标本身（terminal / env 为 null）。
 *   `env` 里的工作目录必须交给 spawn 的环境（`utf8Env(process.env, spec.env)`）——
 *   窗口换到 Windows Terminal 之后，光靠 `spawn({ cwd })` 是传不进去的。
 */
export function consoleStart({
  target,
  args = [],
  dataDir = null,
  cwd = null,
  platform = process.platform,
  env = process.env,
  terminal = null,
} = {}) {
  const plain = { command: String(target), args: args.map(String), launcher: null, terminal: null, env: null };
  if (platform !== 'win32' || !dataDir) return plain;
  const launcher = ensureConsoleLauncher(dataDir);
  if (!launcher) return plain;
  const argv = args.map(String);
  const extraEnv = cwd ? { [CONSOLE_CWD_VAR]: String(cwd) } : null;
  const wt = terminal === 'conhost' ? null : windowsTerminalAlias({ platform, env });
  if (wt) {
    // -w -1：另开一个 Windows Terminal 窗口，不挤进用户已经开着的那个窗口/标签页
    return {
      command: 'cmd',
      args: ['/c', 'start', '', '/min', wt, '-w', '-1', 'cmd', '/c', launcher, String(target), ...argv],
      launcher,
      terminal: 'windows-terminal',
      env: extraEnv,
    };
  }
  // 新开的控制台是「最小化」的：看得见、不挡事，NapCat 自己的脚本仍会再设一次代码页
  return {
    command: 'cmd',
    args: ['/c', 'start', '', '/min', launcher, String(target), ...argv],
    launcher,
    terminal: 'conhost',
    env: extraEnv,
  };
}

export default {
  CONSOLE_LAUNCHER_NAME,
  CONSOLE_CWD_VAR,
  consoleLauncherPath,
  consoleLauncherScript,
  ensureConsoleLauncher,
  utf8Env,
  windowsTerminalAlias,
  consoleStart,
};
